#!/usr/bin/env node
// Generates the `api` schema's types from the local Supabase database into the contract
// package. Never edit the output by hand; CI runs this with --check.
//   node tools/typegen.mjs           write packages/contract/src/database.types.ts
//   node tools/typegen.mjs --check   fail if the committed file is out of date
// Without Docker (cloud sessions), point it at the lite database instead of the stack:
//   TYPEGEN_DB_URL=postgresql://user:pass@localhost:5432/movie_swipe_lite node tools/typegen.mjs
// Lite's `api` schema is the stack's, and the CLI reads it directly with --db-url.
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

import { ROOT } from './lib/roadmap.mjs';

const OUT = `${ROOT}packages/contract/src/database.types.ts`;
const HEADER = '// Generated by tools/typegen.mjs from the local database. Do not edit.\n\n';

const dbUrl = process.env.TYPEGEN_DB_URL;
const command = dbUrl
  ? 'supabase gen types typescript --db-url "$TYPEGEN_DB_URL" --schema api'
  : 'supabase gen types typescript --local --schema api';

let generated;
try {
  generated = execSync(command, {
    cwd: ROOT,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
} catch (error) {
  console.error(
    'Could not generate types: is the local stack running (`supabase start`), or TYPEGEN_DB_URL right?\n' +
      String(error.stderr ?? error.message),
  );
  process.exit(1);
}

const next = HEADER + generated;
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== next) {
    console.error(
      'packages/contract/src/database.types.ts is out of date: run `mise run typegen`.',
    );
    process.exit(1);
  }
  console.log('Generated types are up to date.');
} else {
  writeFileSync(OUT, next);
  console.log('Wrote packages/contract/src/database.types.ts');
}
