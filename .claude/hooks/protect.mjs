#!/usr/bin/env node
// PreToolUse (Edit, Write): refuses edits to files nobody should change by hand.
// Exit code 2 blocks the edit, and Claude reads the reason from stderr.
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { relative } from 'node:path';

const input = JSON.parse(readFileSync(0, 'utf8'));
const file = input.tool_input?.file_path;
if (!file) process.exit(0);

const root = process.env.CLAUDE_PROJECT_DIR ?? input.cwd ?? process.cwd();
const path = relative(root, file);
if (path.startsWith('..')) process.exit(0);

const rules = [
  [/^docs\/archive\//, 'docs/archive/ holds frozen snapshots: never edited.'],
  [
    /(^|\/)\.env(\.local)?$/,
    '.env files hold secrets: Harry sets them. Edit the .env.example instead.',
  ],
  [/^packages\/contract\/src\/database\.types\.ts$/, 'Generated: run `mise run typegen` instead.'],
  [
    /^mobile\/src\/theme\/generated\//,
    'Generated from tokens.json: edit mobile/src/theme/tokens.json, then `mise run tokens`.',
  ],
  [/^mobile\/src\/uniwind-types\.d\.ts$/, 'Generated by Uniwind when Metro runs.'],
  [
    /(^|\/)(pnpm-lock\.yaml|uv\.lock)$/,
    'Lockfiles change only through the package manager (`npx expo install`, `pnpm add`, `uv add`).',
  ],
];
for (const [pattern, reason] of rules) {
  if (pattern.test(path)) {
    console.error(`Blocked: ${path}. ${reason}`);
    process.exit(2);
  }
}

// A migration that's already on main is history: fix forward with a new one.
if (/^supabase\/migrations\/.+\.sql$/.test(path)) {
  try {
    execFileSync('git', ['cat-file', '-e', `origin/main:${path}`], { cwd: root, stdio: 'ignore' });
    console.error(
      `Blocked: ${path} is merged. Write a new migration (\`supabase migration new <name>\`).`,
    );
    process.exit(2);
  } catch {
    // Not on main yet: editing it is fine.
  }
}
process.exit(0);
